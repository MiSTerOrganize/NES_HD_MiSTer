"""Write the ROMs RENDER reads: colour emphasis (rtl/hdpack/hd3_emph_{r,g,b}.hex) and the
default 2C02 palette for packs without palette.dat (rtl/hdpack/hd3_pal2c02.hex, 64 x RRGGBB,
hdref.MESEN_2C02).

hdref.line_effects (Mesen's HD renderer) applies emphasis as floor(c * f) per channel, with f
built in double precision in a fixed order (1.1 for the emphasised channel, 0.9 for the
others, per emphasis bit). Re-deriving that in fixed point risks the cases where c * f lands
on an integer and double rounding decides the floor, so the hardware looks the answer up in a
table generated by the same arithmetic: entry [emph * 256 + c], emph 0..7, c 0..255.
Emphasis 0 is the identity (hdref skips the step).

usage: python make_render_roms.py [outdir]   (default: rtl/hdpack next to this script)
"""
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from hdref import MESEN_2C02  # noqa: E402


def factors(e):
    rf = gf = bf = 1.0
    if e & 1:
        rf *= 1.1
        gf *= 0.9
        bf *= 0.9
    if e & 2:
        gf *= 1.1
        rf *= 0.9
        bf *= 0.9
    if e & 4:
        bf *= 1.1
        rf *= 0.9
        gf *= 0.9
    return rf, gf, bf


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "..", "rtl", "hdpack")
    c = np.arange(256, dtype=np.int32)
    tabs = [[], [], []]
    for e in range(8):
        f = factors(e)
        for ch in range(3):
            if e == 0:
                v = c
            else:
                v = np.minimum(np.floor(c * f[ch]).astype(np.int32), 255)
            tabs[ch] += [int(x) for x in v]
    for ch, name in enumerate("rgb"):
        with open(os.path.join(out, f"hd3_emph_{name}.hex"), "w") as fh:
            fh.write("\n".join(f"{x:02x}" for x in tabs[ch]) + "\n")
    with open(os.path.join(out, "hd3_pal2c02.hex"), "w") as fh:
        fh.write("\n".join(f"{c:06x}" for c in MESEN_2C02) + "\n")
    print("wrote 3 x 2048 emphasis entries and 64 palette entries to", os.path.abspath(out))


if __name__ == "__main__":
    main()
